import { readFile, writeFile } from 'node:fs/promises';
const wgsl = await readFile(new URL('../src/audio-impact.wgsl', import.meta.url), 'utf8');
const type = s => s.replace(/vec([234])<f32>/g, 'metal::float$1');
let source = wgsl.replace(/fn (\w+)\(([^)]*)\) -> ([^{]+)\{/g, (_, name, args, result) => {
  const params = args.split(',').map(arg => { const [name, t] = arg.trim().split(':'); return `${type(t.trim())} ${name}`; });
  return `${type(result.trim())} ${name}(${params.join(', ')}, constant Uniforms& u) {`;
}).replace(/\blet (\w+) =/g, 'auto $1 =');
source = type(source).replace(/\b(sin|pow|max|min|length)\(/g, 'metal::$1(').replaceAll('glsRenderMinSize()', 'glsRenderMinSize(u)');
const path = new URL('../effect.metal', import.meta.url);
let metal = await readFile(path, 'utf8');
metal = metal.replace(/\/\/ BEGIN AUDIO IMPACT[\s\S]*?\/\/ END AUDIO IMPACT\n\n/g, '');
metal = metal.replace('// BEGIN ORBIT RINGS', `// BEGIN AUDIO IMPACT\n// Generated by scripts/sync-audio-impact.mjs.\n${source}// END AUDIO IMPACT\n\n// BEGIN ORBIT RINGS`);
await writeFile(path, metal);
