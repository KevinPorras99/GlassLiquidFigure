// Keep the small analytic ring shader identical in WebGPU and Swift/Metal.
import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../src/orbit-rings.wgsl', import.meta.url), 'utf8');
const type = value => value.replace(/vec([234])<f32>/g, 'metal::float$1').replace(/\bf32\b/g, 'float');
let metal = source
  .replace(/fn (\w+)\(([^)]*)\) -> ([^{]+)\{/g, (_, name, args, result) => {
    const parameters = args.split(',').filter(Boolean).map(arg => {
      const [name, value] = arg.trim().split(':');
      return `${type(value.trim())} ${name}`;
    });
    if (name === 'orbitRingHit' || name === 'orbitRingsColor') parameters.push('constant Uniforms& u');
    return `${type(result.trim())} ${name}(${parameters.join(', ')}) {`;
  })
  .replace(/(\w+): (vec[234]<f32>|f32),/g, (_, name, value) => `${type(value)} ${name};`)
  .replace(/\bvar (\w+): (\w+);/g, '$2 $1;')
  .replace(/\b(?:let|var) (\w+) =/g, 'auto $1 =');
metal = type(metal)
  .replace(/\b(cos|sin|abs|min|max|sqrt|dot|pow|floor|normalize|atan2|clamp|length|fwidth|smoothstep|fract|mix)\(/g, 'metal::$1(')
  .replace(/glsRenderMinSize\(\)/g, 'glsRenderMinSize(u)')
  .replace(/orbitRingHit\(uv, ([012]\.0)\)/g, 'orbitRingHit(uv, $1, u)');
const path = new URL('../effect.metal', import.meta.url);
let target = await readFile(path, 'utf8');
target = target.replace(/\/\/ BEGIN ORBIT RINGS[\s\S]*?\/\/ END ORBIT RINGS\n\n/g, '');
target = target.replace('struct fs_mainOutput {', `// BEGIN ORBIT RINGS\n// Generated by scripts/sync-orbit-rings.mjs from src/orbit-rings.wgsl.\n${metal}\n// END ORBIT RINGS\n\nstruct fs_mainOutput {`);
await writeFile(path, target);
