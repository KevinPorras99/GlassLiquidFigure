// Generate the Metal solid preview directly from the editor's WGSL functions.
import { readFile, writeFile } from 'node:fs/promises';
const shader = await readFile(new URL('../src/shader-source.ts', import.meta.url), 'utf8');
let source = shader.slice(shader.indexOf('fn viewToObject('), shader.indexOf('@fragment\nfn fs_main'))
  .replace('return prRotateX(prRotateY(p, -u.shape.z), -u.shape.y);', 'return orbitRingRotate(p, u.shape.z, u.shape.y);')
  .replace('fn solidColor(in: VOut)', 'fn solidColor(uv: vec2<f32>)')
  .replaceAll('in.uv', 'uv');
const calls = /\b(viewToObject|solidDistance|glsShapeDistance|glsSacredDistance|glsAuraBehind|glsPresetFluid)\(/g;
const insertions = [];
for (const match of source.matchAll(calls)) {
  if (/fn\s+$/.test(source.slice(Math.max(0, match.index - 5), match.index))) continue;
  let depth = 1, end = match.index + match[0].length;
  while (depth > 0) {
    if (source[end] === '(') depth++;
    if (source[end] === ')') depth--;
    end++;
  }
  insertions.push(end - 1);
}
for (const offset of insertions.sort((a, b) => b - a)) source = source.slice(0, offset) + ', u' + source.slice(offset);
const type = value => value.replace(/vec([234])<f32>/g, 'metal::float$1').replace(/\bf32\b/g, 'float').replace(/\bi32\b/g, 'int');
source = source
  .replace(/fn (\w+)\(([^)]*)\) -> ([^{]+)\{/g, (_, name, args, result) => {
    const parameters = args.split(',').map(arg => {
      const [name, value] = arg.trim().split(':');
      return `${type(value.trim())} ${name}`;
    });
    return `${type(result.trim())} ${name}(${parameters.join(', ')}, constant Uniforms& u) {`;
  })
  .replace(/\bvar (\w+): f32;/g, 'float $1;')
  .replace(/\b(?:let|var) (\w+) =/g, 'auto $1 =')
  .replace(/select\(0.28, 0.016, sacred\)/g, '(sacred ? 0.016 : 0.28)')
  .replace(/select\(0.025, 0.002, sacred\)/g, '(sacred ? 0.002 : 0.025)');
source = type(source)
  .replace(/\b(abs|min|max|length|normalize|dot|pow|clamp)\(/g, 'metal::$1(')
  .replaceAll('glsRenderMinSize()', 'glsRenderMinSize(u)');
const path = new URL('../effect.metal', import.meta.url);
let metal = await readFile(path, 'utf8');
metal = metal.replace(/\/\/ BEGIN SOLID SHAPE[\s\S]*?\/\/ END SOLID SHAPE\n\n/g, '');
metal = metal.replace('struct fs_mainOutput {', `// BEGIN SOLID SHAPE\n// Generated by scripts/sync-solid-shape.mjs.\n${source}// END SOLID SHAPE\n\nstruct fs_mainOutput {`);
await writeFile(path, metal);
